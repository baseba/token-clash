export function trainerSpriteFor(seed, pool = TRAINER_SPRITES) {
  let hash = 0;
  for (const ch of String(seed)) hash = (Math.imul(hash, 31) + ch.codePointAt(0)) >>> 0;
  return pool[hash % pool.length];
}
